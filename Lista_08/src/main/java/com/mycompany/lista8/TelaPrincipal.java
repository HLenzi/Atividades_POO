    private void jBtnListarAlunoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnListarAlunoActionPerformed
        ListarTurma telaListar = new ListarTurma(this, true);
        Turno turno = null;
        Titulacao titulacao = null;
        
        if(jRbtnMatutino.isSelected()){
            turno = Turno.MATUTINO;
        } else if(jRbtnVespertino.isSelected()){
            turno = Turno.VESPERTINO;
        } else if(jRbtnNoturno.isSelected()){
            turno = Turno.NOTURNO;
        }
        
        if(jRbtnGraduacao.isSelected()){
            titulacao = Titulacao.GRADUACAO;
        } else if(jRbtnMestrado.isSelected()){
            titulacao = Titulacao.MESTRADO;
        } else if(jRbtnDoutorado.isSelected()){
            titulacao = Titulacao.DOUTORADO;
        }
        
        telaListar.jTextArea.append("Disciplina: " + jTfDisciplina.getText());
        telaListar.jTextArea.append("\nTurno: ");
        switch (turno) {
            case MATUTINO:
                telaListar.jTextArea.append("Matutino");
                break;
            case VESPERTINO:
                telaListar.jTextArea.append("Vespertino");
                break;
            case NOTURNO:
                telaListar.jTextArea.append("Noturno");
                break;
            default:
                throw new IllegalArgumentException("Turno?");
        }
        telaListar.jTextArea.append("\n----------------------------");
        
        telaListar.jTextArea.append("\nProfessor: " + jTfNomeProfessor.getText());
        switch (titulacao) {
            case GRADUACAO:
                telaListar.jTextArea.append("Graduação");
                break;
            case MESTRADO:
                telaListar.jTextArea.append("Mestrado");
                break;
            case DOUTORADO:
                telaListar.jTextArea.append("Doutorado");
                break;
            default:
                throw new IllegalArgumentException("Titulo?");
        }
        telaListar.jTextArea.append("\nEmail: " + jTfEmail.getText());
        
        telaListar.jTextArea.append("\n----------------------------");
        
        
        telaListar.jTextArea.append("\nTotal de Aluno: " + listaAlunos.size());
        
        for (Aluno aluno: listaAlunos){
            telaListar.jTextArea.append("\n" + aluno.getNome() + "    Matricula: " + aluno.getMatricula() + "  Nota Enem: " + aluno.getNotaEnem());
        }
        
        
        
        
        
        
        
        
        telaListar.setVisible(true);
        
        
    }//GEN-LAST:event_jBtnListarAlunoActionPerformed

